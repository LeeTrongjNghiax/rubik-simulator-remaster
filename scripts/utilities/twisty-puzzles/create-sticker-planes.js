import createStickerPlaneInOneAxis from "./create-sticker-plane-in-one-axis.js";

const createStickerPlanes = ({
  planeMatrix = new Float32Array(16), 
  startWidth = 0,
  endWidth = 0,
  translationX = 0,
  startHeight = 0,
  endHeight = 0,
  translationY = 0,
  startDepth = 0,
  endDepth = 0,
  translationZ = 0,
  twistyPuzzleCubieHalfLength = 0.5, 
  stickerGap = 0.1,
  stickerSize = 0.9999,
  stickerTopColor = [1, 1, 1],
  stickerBottomColor = [1, 1, 0],
  stickerFrontColor = [0, 1, 1],
  stickerBackColor = [0, 0, 1],
  stickerRightColor = [1, 0, 0],
  stickerLeftColor = [1, 0.65, 0],
  stickerInnerTopColor = [1, 1, 1],
  stickerInnerBottomColor = [1, 1, 0],
  stickerInnerFrontColor = [0, 1, 1],
  stickerInnerBackColor = [0, 0, 1],
  stickerInnerRightColor = [1, 0, 0],
  stickerInnerLeftColor = [1, 0.65, 0],
  stickerColorTransparency = 1,
  stickerInnerColorTransparency = 1,
}) => {
  const planesX = createStickerPlaneInOneAxis({
    positions: [ planeMatrix[0], planeMatrix[1], planeMatrix[2] ],
    defaultPositions: [1, 0, 0],
    start: startWidth,
    end: endWidth,
    translation: translationX,
    twistyPuzzleCubieHalfLength,
    stickerGap,
    stickerSize,
    stickerStartColorName: `right`,
    stickerInnerStartColorName: `inner-right`,
    stickerEndColorName: `left`,
    stickerInnerEndColorName: `inner-left`,
    stickerStartColor: stickerRightColor,
    stickerInnerStartColor: stickerInnerRightColor,
    stickerEndColor: stickerLeftColor,
    stickerInnerEndColor: stickerInnerLeftColor,
    colorTransparency: stickerColorTransparency,
    innerColorTransparency: stickerInnerColorTransparency,
  });

  const planesY = createStickerPlaneInOneAxis({
    positions: [ planeMatrix[3], planeMatrix[4], planeMatrix[5] ],
    defaultPositions: [0, 1, 0],
    start: startHeight,
    end: endHeight,
    translation: translationY,
    twistyPuzzleCubieHalfLength,
    stickerGap,
    stickerSize,
    stickerStartColorName: `down`,
    stickerInnerStartColorName: `inner-down`,
    stickerEndColorName: `up`,
    stickerInnerEndColorName: `inner-up`,
    stickerStartColor: stickerBottomColor,
    stickerInnerStartColor: stickerInnerBottomColor,
    stickerEndColor: stickerTopColor,
    stickerInnerEndColor: stickerInnerTopColor,
    colorTransparency: stickerColorTransparency,
    innerColorTransparency: stickerInnerColorTransparency,
  });

  const planesZ = createStickerPlaneInOneAxis({
    positions: [ planeMatrix[6], planeMatrix[7], planeMatrix[8] ],
    defaultPositions: [0, 0, 1],
    start: startDepth,
    end: endDepth,
    translation: translationZ,
    twistyPuzzleCubieHalfLength,
    stickerGap,
    stickerSize,
    stickerStartColorName: `front`,
    stickerInnerStartColorName: `inner-front`,
    stickerEndColorName: `back`,
    stickerInnerEndColorName: `inner-back`,
    stickerStartColor: stickerFrontColor,
    stickerInnerStartColor: stickerInnerFrontColor,
    stickerEndColor: stickerBackColor,
    stickerInnerEndColor: stickerInnerBackColor,
    colorTransparency: stickerColorTransparency,
    innerColorTransparency: stickerInnerColorTransparency,
  });

  return [planesX, planesY, planesZ];
};

export default createStickerPlanes;
